-- =====================================================================
-- ENQUETES DE VOTAÇÃO (Individual SIM/NÃO e Disputa entre opções)
-- Execute este script no SQL Editor do Supabase.
-- =====================================================================

create table if not exists public.enquetes (
    id bigint generated by default as identity primary key,
    titulo text not null,
    descricao text,
    tipo text not null check (tipo in ('individual', 'disputa')),
    status text not null default 'Aguardando' check (status in ('Aguardando', 'Em votação', 'Encerrada')),
    data_inicio timestamptz,
    data_fim timestamptz,
    criado_em timestamptz not null default now()
);

create table if not exists public.enquete_opcoes (
    id bigint generated by default as identity primary key,
    enquete_id bigint not null references public.enquetes(id) on delete cascade,
    titulo text not null,
    ordem integer not null default 1
);

create table if not exists public.enquete_votos (
    id bigint generated by default as identity primary key,
    enquete_id bigint not null references public.enquetes(id) on delete cascade,
    opcao_id bigint not null references public.enquete_opcoes(id) on delete cascade,
    cpf text not null,
    inscrito_id text,
    -- 'SIM' / 'NAO' para enquete individual; NULL para enquete de disputa
    voto text check (voto in ('SIM', 'NAO')),
    user_agent text,
    data_hora timestamptz not null default now()
);

create index if not exists enquete_opcoes_enquete_idx on public.enquete_opcoes (enquete_id);
create index if not exists enquete_votos_enquete_idx on public.enquete_votos (enquete_id);

-- Anti-duplicidade garantida pelo banco:
-- Individual: 1 voto por CPF em cada item
create unique index if not exists enquete_votos_individual_uniq
    on public.enquete_votos (opcao_id, cpf) where voto is not null;
-- Disputa: 1 voto por CPF na enquete inteira
create unique index if not exists enquete_votos_disputa_uniq
    on public.enquete_votos (enquete_id, cpf) where voto is null;

-- RLS (mesmo modelo de acesso público já usado nas tabelas de votação de Tese)
alter table public.enquetes enable row level security;
alter table public.enquete_opcoes enable row level security;
alter table public.enquete_votos enable row level security;

drop policy if exists "enquetes_all" on public.enquetes;
create policy "enquetes_all" on public.enquetes for all using (true) with check (true);

drop policy if exists "enquete_opcoes_all" on public.enquete_opcoes;
create policy "enquete_opcoes_all" on public.enquete_opcoes for all using (true) with check (true);

drop policy if exists "enquete_votos_select" on public.enquete_votos;
create policy "enquete_votos_select" on public.enquete_votos for select using (true);

drop policy if exists "enquete_votos_insert" on public.enquete_votos;
create policy "enquete_votos_insert" on public.enquete_votos for insert with check (
    exists (select 1 from public.enquetes e where e.id = enquete_id and e.status = 'Em votação')
);

drop policy if exists "enquete_votos_delete" on public.enquete_votos;
create policy "enquete_votos_delete" on public.enquete_votos for delete using (true);

-- Realtime (gráfico ao vivo)
do $$
begin
    begin alter publication supabase_realtime add table public.enquetes; exception when duplicate_object then null; end;
    begin alter publication supabase_realtime add table public.enquete_opcoes; exception when duplicate_object then null; end;
    begin alter publication supabase_realtime add table public.enquete_votos; exception when duplicate_object then null; end;
end $$;

